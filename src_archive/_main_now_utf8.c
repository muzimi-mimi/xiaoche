void Angle_Realign(void)
{
    int32_t  sum = 0;
    int      k;
    uint32_t itWasOn;

    /* 锟斤拷锟斤拷锟节硷拷要锟斤拷锟斤拷 TIM3 锟叫断ｏ拷锟叫讹拷锟斤拷也锟斤拷锟?MPU6050(同一锟斤拷 I2C)锟斤拷
     * 锟斤拷锟竭诧拷锟斤拷锟结互锟斤拷锟狡伙拷时锟斤拷锟斤拷锟斤拷只锟斤拷 DIER 锟斤拷 UIE 位锟斤拷锟斤拷锟斤拷锟斤拷锟斤拷状态锟斤拷
     * 锟斤拷锟斤拷锟襟按斤拷锟斤拷前锟斤拷原状锟街革拷锟斤拷锟斤拷锟斤拷锟较碉拷锟绞硷拷锟斤拷锟斤拷锟斤拷锟斤拷械锟斤拷枚锟斤拷锟斤拷茫锟斤拷锟?*/
    itWasOn = (htim3.Instance->DIER & TIM_IT_UPDATE) ? 1u : 0u;
    __HAL_TIM_DISABLE_IT(&htim3, TIM_IT_UPDATE);

    for (k = 0; k < 30; k++)              /* 30 x 10ms = 300ms */
    {
        MPU6050_GetData(&AX, &AY, &AZ, &GX, &GY, &GZ);
        sum += (int32_t)(-atan2(AY, AZ) / 3.14159 * 180.0);
        HAL_Delay(10);
    }

    Angle = (float)sum / 30.0f + G;       /* 取平锟斤拷锟斤拷锟斤拷锟斤拷锟接伙拷械锟斤拷锟狡拷锟?*/

    if (itWasOn)
    {
        __HAL_TIM_CLEAR_IT(&htim3, TIM_IT_UPDATE);
        __HAL_TIM_ENABLE_IT(&htim3, TIM_IT_UPDATE);
    }
}

